/**
 * Иконка по имени. Возвращает готовую строку SVG.
 * @param {string} name — ключ из ICONS
 * @param {number} size — размер в пикселях, по умолчанию 22
 */
export function icon(name, size = 22) {
  const svg = ICONS[name];
  if (!svg) return "";
  return svg.replace("<svg ", `<svg width="${size}" height="${size}" aria-hidden="true" `);
}

