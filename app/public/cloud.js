/**
 * Облако частиц на экране записи.
 *
 * Тысяча двести точек, которые дышат в покое, отзываются на громкость голоса
 * и складываются в фигуры: галочку, часы, знак вопроса, улыбку.
 *
 * ── Как это работает ────────────────────────────────────────────────────
 *
 * Каждая частица живёт по формуле — угол, радиус, своя фаза колебания.
 * Поэтому их может быть сколько угодно, и никто не расставляет точки руками.
 *
 * Чтобы собрать фигуру, она рисуется на невидимом холсте, оттуда берутся
 * координаты закрашенных пикселей, и каждая частица получает свою цель.
 * Дальше она просто плывёт к ней и продолжает чуть подрагивать на месте —
 * иначе фигура выглядит замороженной.
 *
 * ── Использование ───────────────────────────────────────────────────────
 *
 *   const cloud = createCloud(canvas);
 *   cloud.setMode("listening");        // покой → слушает
 *   cloud.setLevel(0.7);               // громкость микрофона, 0..1
 *   cloud.showShape("check");          // собрать галочку
 *   cloud.destroy();                   // при уходе с экрана — обязательно
 *
 * ── Важно ───────────────────────────────────────────────────────────────
 *
 * Улыбку нельзя показывать на тяжёлых темах. Проверять через isHeavy()
 * из lib/voice.js — та же функция, что глушит юмор в репликах.
 */

/** Сколько частиц. На слабых телефонах уменьшается автоматически. */
function particleCount() {
  const cores = navigator.hardwareConcurrency || 4;
  if (cores <= 4) return 400;
  if (cores <= 6) return 800;
  return 1200;
}

/**
 * Точки фигуры. Части рисуются по отдельности, и каждая точка помнит,
 * из какой части она пришла.
 *
 * Это важно: делить точки по расстоянию от центра нельзя. Граница режет
 * сами фигуры — закруглённый кончик стрелки выходит за порог и начинает
 * двигаться не со своей частью. Пометка при сборе снимает вопрос совсем.
 *
 * Точка: [x, y, номер части].
 */
function shapePoints(w, h, shape, step = 4) {
  const parts = shape.parts || [{ draw: shape.draw }];
  const points = [];
  for (let n = 0; n < parts.length; n += 1) {
    const off = document.createElement("canvas");
    off.width = w;
    off.height = h;
    const ctx = off.getContext("2d");
    ctx.fillStyle = "#fff";
    ctx.strokeStyle = "#fff";
    parts[n].draw(ctx, w / 2, h / 2);
    const data = ctx.getImageData(0, 0, w, h).data;
    for (let y = 0; y < h; y += step) {
      for (let x = 0; x < w; x += step) {
        if (data[(y * w + x) * 4 + 3] > 128) points.push([x, y, n]);
      }
    }
  }
  return points;
}

