/**
 * Голос приложения.
 *
 * Здесь живут все фразы, которыми SoulVoice разговаривает с человеком.
 * Логика их не касается: server.js передаёт ключ и подстановки, а как это
 * прозвучит — решается тут. Значит формулировки можно править, не трогая код.
 *
 * ── Характер ────────────────────────────────────────────────────────────
 *
 * Внимательная, спокойная, с юмором, иногда прямая. Говорит предложениями,
 * а не двумя словами. На «ты».
 *
 * Тепло делается из фактов, а не из выдуманных чувств. Приложение не ждёт,
 * не скучает и не устаёт — но оно правда считает дела, правда видит, что
 * запись переносят третий раз, и правда замечает, что человек не заходил
 * три дня. Вот из этого и получается «кто-то за меня переживает».
 *
 * Нельзя: «я скучала», «я с тобой умоталась», «мне тоже тяжело».
 * Можно:  «три дня тебя не было», «денёк был, да?», «если что — я рядом».
 *
 * ── Как править ─────────────────────────────────────────────────────────
 *
 * Просто меняйте строки в таблицах ниже. Требования всего два:
 *   1. В каждом наборе не меньше пяти вариантов — иначе приедается.
 *   2. Подстановки в фигурных скобках должны остаться на месте.
 *
 * Спокойных вариантов держите большинство. Тёплое и смешное — редкие
 * вкрапления, которые замечаешь именно потому, что они редкие. Если
 * сомневаетесь между тёплым и спокойным — берите спокойный.
 */

