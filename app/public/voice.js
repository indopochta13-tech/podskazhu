/**
 * Склонение существительного при числе: 1 дело, 2 дела, 5 дел.
 * Без этого приложение регулярно писало бы «2 дел» — мелочь, по которой
 * сразу видно, что текст собирала машина.
 */
export function plural(n, one, few, many) {
  const abs = Math.abs(Number(n) || 0);
  const tail100 = abs % 100;
  const tail10 = abs % 10;
  if (tail100 >= 11 && tail100 <= 14) return `${n} ${many}`;
  if (tail10 === 1) return `${n} ${one}`;
  if (tail10 >= 2 && tail10 <= 4) return `${n} ${few}`;
  return `${n} ${many}`;
}

/** Готовые подстановки для частых случаев. */
export const count = {
  дел: n => plural(n, "дело", "дела", "дел"),
  дней: n => plural(n, "день", "дня", "дней"),
  записей: n => plural(n, "запись", "записи", "записей"),
};

/** Последняя выданная реплика по каждому ключу — чтобы не повторяться подряд. */
const lastUsed = new Map();

function fill(line, vars) {
  // Имена подстановок русские ({когда}, {что}), поэтому \w здесь не годится:
  // в JavaScript он покрывает только латиницу.
  return String(line).replace(/\{([^{}\s]+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole);
}

/**
 * Реплика по ключу.
 *
 * @param {string} key    ключ из LINES
 * @param {object} opts   { voice, vars, calm, calmKey }
 */
export function say(key, opts = {}) {
  const voice = opts.voice === "he" ? "he" : "she";
  const vars = opts.vars || {};

  if (opts.calm) {
    const line = CALM[voice][opts.calmKey || "created"] || CALM[voice].created;
    return fill(line, vars);
  }

  const set = LINES[key]?.[voice];
  if (!set || !set.length) return "";

  let pick = set[Math.floor(Math.random() * set.length)];
  if (set.length > 1 && pick === lastUsed.get(key)) {
    // Тот же вариант подряд — берём соседний, чтобы не приедалось.
    pick = set[(set.indexOf(pick) + 1) % set.length];
  }
  lastUsed.set(key, pick);
  return fill(pick, vars);
}

/** Наблюдение по ключу. Возвращает пустую строку в спокойном режиме. */
export function note(key, opts = {}) {
  if (opts.calm) return "";
  const voice = opts.voice === "he" ? "he" : "she";
  const set = NOTES[key]?.[voice];
  if (!set || !set.length) return "";
  const pick = set[Math.floor(Math.random() * set.length)];
  return fill(pick, opts.vars || {});
}
