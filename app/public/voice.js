/**
 * Спокойный режим.
 *
 * Если человек записывает что-то тяжёлое, шутить нельзя. Совсем.
 * Ответ короткий и деловой, наблюдения не показываем.
 *
 * Это не украшение, а обязательная часть: приложение, которое заговорило
 * по-человечески, рано или поздно получит запись про больницу или похороны.
 * Шутка про кофе в этот момент — то, за что удаляют навсегда.
 */
/** Границы слова для кириллицы: \b в JavaScript с русскими буквами не работает. */
const RU = "а-яёА-ЯЁ";
const NBL = `(?<![${RU}])`;
const NB = `(?![${RU}])`;

const HEAVY_RE = new RegExp(
  "похорон|поминк|кладбищ|умер|смерт|скончал"
  + "|больниц|реанимац|операци|онколог|химиотерап|диагноз|биопси"
  + "|развод|расстал|повестк"
  // «суд» отдельным словом: без границ шаблон цеплял бы «посуду» и «рассуждать»
  + `|${NBL}суд(?:${NB}|е${NB}|а${NB}|ом${NB}|ебн)`
  + "|уволил|сократил|увольнен",
  "iu");

export function isHeavy(text) {
  return HEAVY_RE.test(String(text || ""));
}

