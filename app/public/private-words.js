/**
 * Признаки лекарства и косметики в тексте записи.
 *
 * Названия препаратов и средств живут только на телефоне: сервер их забывает.
 * Раньше это решала полка — «Витамины» и «Уход». Но фраза «принимать флуоксетин
 * 20 миллиграмм» уезжает в дела, и название препарата оставалось на сервере
 * навсегда. Полка — не гарантия приватности, поэтому смотрим ещё и на слова.
 *
 * Правило намеренно осторожное: ошибка в одну сторону стоит человеку строчки
 * «название осталось на прежнем телефоне» после переноса аккаунта, поэтому
 * забываем только то, что похоже на лекарство или средство наверняка.
 *
 * Модуль общий: сервер зовёт его из forget-titles, приложение — когда решает,
 * какие записи отправить на забывание.
 */

/** Само по себе не бывает ничем другим: лекарство или уходовое средство. */
const SURE = new RegExp([
  "витамин", "таблетк", "капсул", "лекарств", "препарат", "антибиотик",
  "мазь", "мази", "\\bбад\\b", "ампул", "инъекц", "антидепрессант",
  "ноотроп", "инсулин", "ингалятор", "суспензи", "микстур", "драже",
  "ретино", "сыворотк", "санскрин", "\\bspf\\b", "\\bспф\\b", "пилинг",
  "мицелляр", "гиалурон", "ниацинамид", "салицилов", "азелаинов",
  "антигистамин", "жаропонижа", "обезболива",
].join("|"), "i");

/** Требует глагола приёма рядом: сами по себе это обычные слова. */
const MAYBE = /(крем|гель|спрей|капли|капель|лосьон|сироп|порошок|маск[аиу]|патч|флюид|эмульси|тоник|скраб|курс)/i;

/** Глаголы приёма и нанесения. */
const INTAKE = /(принима|принять|прими|пить|выпить|пропить|попить|наноси|нанести|намаза|мазать|мажь|капать|закапа|колоть|уколоть|пшика|втира)/i;

/** Дозировка: «20 мг», «0,5 мл», «400 ме», «2 %». */
const DOSE = /\d+[.,]?\d*\s*(мг|мкг|мл|ме\b|ед\b|iu\b|%|миллиграмм|микрограмм|миллилитр)/i;

/** Еда и питьё: «выпить 200 мл воды» — не лекарство. */
const FOOD = /(вод[аыуе]|воды|чай|кофе|сок\b|молок|компот|бульон|\bсуп|каш[аиу])/i;

/**
 * Похоже ли, что в тексте есть название препарата или средства.
 * @param {string} text — название записи и исходная фраза вместе.
 */
export function looksPrivate(text) {
  const s = String(text || "");
  if (!s.trim()) return false;
  if (SURE.test(s)) return true;
  if (!INTAKE.test(s)) return false;
  if (FOOD.test(s)) return false;
  return DOSE.test(s) || MAYBE.test(s);
}

/** Текстовые поля записи, в которых может оказаться название. */
export const PRIVATE_TEXT_FIELDS = ["title", "place", "who", "phone", "note", "source"];

/** Собрать текст записи для проверки. */
export function itemPrivateText(item) {
  return PRIVATE_TEXT_FIELDS.map(f => String(item?.[f] || "")).join(" ");
}
