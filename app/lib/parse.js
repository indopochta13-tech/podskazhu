function minuteWords(raw) {
  const parts = normalize(String(raw || "")).trim().split(/\s+/);
  if (parts.length === 2 && (parts[0] === "ноль" || parts[0] === "нуль")) return 0;
  const tens = wordNumber(parts[0]);
  if (tens == null) return null;
  if (parts.length === 1) return tens <= 59 ? tens : null;
  const ones = wordNumber(parts[1]);
  if (ones == null) return null;
  const value = tens + ones;
  return value <= 59 ? value : null;
}

// Минуты в родительном падеже для «без …»: одно слово («пятнадцати») или
// десятки с единицами («двадцати пяти» = 25).
function genitiveMinutes(raw) {
  const parts = normalize(String(raw || "")).trim().split(/\s+/).filter(Boolean);
  if (!parts.length) return null;
  if (parts.length === 1) {
    return /^\d+$/.test(parts[0]) ? Number(parts[0]) : wordNumber(parts[0]);
  }
  if (parts.length > 2) return null;
  const tens = wordNumber(parts[0]);
  const ones = wordNumber(parts[1]);
  if (tens == null || ones == null) return null;
  if (tens < 20 || tens % 10 !== 0 || ones > 9) return null;
  return tens + ones;
}

