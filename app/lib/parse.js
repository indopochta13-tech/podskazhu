function ordinalDay(tens, word) {
  const base = ORDINAL_DAY_UNITS[word];
  if (base == null) return null;
  if (!tens) return base;
  if (base > 9) return null;
  const value = (tens === "двадцать" ? 20 : 30) + base;
  return value <= 31 ? value : null;
}

