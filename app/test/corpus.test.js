let failed = 0;
const rows = [];
const bySection = new Map();

const fmtDate = d => (d ? `${String(d.day).padStart(2, "0")}.${String(d.month + 1).padStart(2, "0")}` : "—");
const fmtTime = t => (t ? `${String(t.hour).padStart(2, "0")}:${String(t.minute).padStart(2, "0")}` : "—");

function actual(result) {
  const first = result.drafts?.[0];
  if (!first) return { n: 0, intent: result.intent, type: result.intent, title: "", date: null, time: null, place: "", repeat: null };
  return {
    n: result.drafts.length,
    intent: result.intent,
    type: first.type,
    title: first.title,
    date: first.date,
    time: first.time,
    place: first.place,
    repeat: first.repeat,
  };
}

/** Ожидание словами — чтобы в отчёте было видно, чего мы вообще хотели. */
function wantText(w) {
  const bits = [];
  if (w.intent) bits.push(`intent:${w.intent}`);
  if (w.type) bits.push(w.type);
  if (w.n) bits.push(`дел:${w.n}`);
  if (w.d) bits.push(w.d);
  if (w.h != null) bits.push(`${String(w.h).padStart(2, "0")}:${String(w.mi ?? 0).padStart(2, "0")}`);
  if (w.noTime) bits.push("без времени");
  if (w.place) bits.push(`место~${w.place}`);
  if (w.title) bits.push(`назв~${w.title}`);
  if (w.notitle) bits.push(`назв!~${w.notitle}`);
  if (w.repeat) bits.push(`повтор:${w.repeat}`);
  return bits.join(" ");
}

function gotText(g) {
  const bits = [g.type];
  if (g.n !== 1) bits.push(`дел:${g.n}`);
  if (g.date) bits.push(fmtDate(g.date));
  bits.push(fmtTime(g.time));
  if (g.place) bits.push(`место:${g.place}`);
  bits.push(`«${g.title}»`);
  if (g.repeat) bits.push(`повтор:${g.repeat.kind}`);
  return bits.join(" ");
}

/** Что именно разошлось — по названию поля, а не «не совпало». */
function mismatches(w, g) {
  const bad = [];
  if (w.intent && g.intent !== w.intent) bad.push("intent");
  if (w.type && g.type !== w.type) bad.push("тип");
  if (w.n && g.n !== w.n) bad.push("кол-во дел");
  if (w.d && fmtDate(g.date) !== w.d) bad.push("дата");
  if (w.h != null && (!g.time || g.time.hour !== w.h || g.time.minute !== (w.mi ?? 0))) bad.push("время");
  if (w.noTime && g.time) bad.push("лишнее время");
  if (w.place && !new RegExp(w.place, "i").test(g.place || "")) bad.push("место");
  if (w.title && !new RegExp(w.title, "i").test(g.title || "")) bad.push("название");
  if (w.notitle && new RegExp(w.notitle, "i").test(g.title || "")) bad.push("мусор в названии");
  if (w.repeat && (g.repeat?.kind || "—") !== w.repeat) bad.push("повтор");
  return bad;
}

const verbose = Boolean(process.env.VERBOSE);
console.log(`Корпус живой речи: ${CORPUS.length} фраз\n`);

for (const c of CORPUS) {
  const ctx = CTX[c.ctx || "sun"];
  let got;
  let bad;
  try {
    got = actual(parse(c.t, ctx));
    bad = mismatches(c.w, got);
  } catch (err) {
    got = null;
    bad = [`исключение: ${err.message}`];
  }
  if (bad.length) failed += 1;
  rows.push({ s: c.s, t: c.t, want: wantText(c.w), got: got ? gotText(got) : "—", bad });
  const st = bySection.get(c.s) || { total: 0, ok: 0 };
  st.total += 1;
  if (!bad.length) st.ok += 1;
  bySection.set(c.s, st);
}

let section = null;
for (const r of rows) {
  if (!verbose && !r.bad.length) continue;
  if (r.s !== section) {
    section = r.s;
    console.log(`— ${section} —`);
  }
  if (r.bad.length) {
    console.log(`  ✗ «${r.t}»`);
    console.log(`      ждали: ${r.want}`);
    console.log(`      вышло: ${r.got}   → ${r.bad.join(", ")}`);
  } else {
    console.log(`  ✓ «${r.t}» → ${r.got}`);
  }
}

console.log(verbose ? "" : failed ? "" : "  промахов нет\n");
for (const [s, st] of bySection) {
  console.log(`${st.ok === st.total ? "✓" : "✗"} ${s}: ${st.ok}/${st.total}`);
}
const ok = CORPUS.length - failed;
console.log(`\nВерно ${ok} из ${CORPUS.length}` + (failed ? `, промахов ${failed}` : ""));

process.exit(failed ? 1 : 0);
